/* ===========================================================
   요금 칩 — 상품 목록(홈·투어) 카드에 붙는 작은 금액 딱지
   -----------------------------------------------------------
   예전에는 price 글자("1인 80유로 (4인 이상 출발 기준)")를
   그대로 찍었습니다. 지금은 상품마다 '요금' 자료가 들어 있어서
   상세 쪽과 목록 카드가 따로 놀게 되었습니다.

   그래서 아래처럼 한 군데서 정리합니다.
     ① '요금' 자료가 있으면 그 금액으로
     ② 아직 '요금'을 안 적었으면 예전 price 글자에서 숫자를 찾아서
     ③ 그래도 금액이 없으면 '가격 문의' 단추로
   어느 쪽이든 카드에 보이는 모양은 하나로 같습니다.
   =========================================================== */

/* '1인 80유로 (4인 이상 출발 기준)' → { 값:80, 단위:'1인', 덧말:'4인 이상 출발 기준' } */
function euPriceToFare(price){
  const p = String(price || '').trim();
  if(!p || p.indexOf('문의') !== -1) return null;

  const m = p.match(/([0-9][0-9,]*(?:\.[0-9]+)?)\s*(?:유로|EUR)/i) ||
            p.match(/€\s*([0-9][0-9,]*(?:\.[0-9]+)?)/);
  if(!m) return null;
  const 값 = parseFloat(m[1].replace(/,/g, ''));
  if(!isFinite(값)) return null;

  const 단위 = (p.match(/([0-9]+\s*인|1\s*팀|1\s*대)/) || [])[1];
  const 괄호 = p.match(/\(([^)]*)\)/);
  return {
    '꼴': '한줄',
    '값': 값,
    '단위': (단위 || '1인').replace(/\s+/g, ''),
    '덧말': 괄호 ? 괄호[1].trim() : ''
  };
}

function euCardMoney(값){
  if(값 == null || !isFinite(값)) return '';
  /* 요금은 소수점을 떼고 보여 줍니다 — 계산은 원래 값 그대로 합니다 */
  return '€' + Math.round(Number(값)).toLocaleString('en-US');
}

/* 계산기 요금(여러 날 패키지)에서 가장 싼 금액을 꺼냅니다 — '…부터' 로 보여 주려고요 */
function euFareLowest(f){
  const 값들 = (f && f['구간'] || [])
    .map(function(g){ return g && g['값']; })
    .filter(function(v){ return v != null && isFinite(v); });
  return 값들.length ? Math.min.apply(null, 값들) : null;
}

function euFareChip(p){
  const f = (p && p['요금']) || null;
  let 값 = null, 단위 = '', 덧말 = '', 부터 = false;

  if(f && f['꼴'] === '계산기'){
    값 = euFareLowest(f);
    단위 = f['단위'] || '1인';
    부터 = (값 != null);
  } else if(f){
    값 = f['값'];
    단위 = f['단위'] || '1인';
    덧말 = f['덧말'] || '';
  }

  /* 아직 '요금'에 값이 없으면 예전 price 글자에 적힌 금액이라도 씁니다 */
  if(값 == null){
    const g = euPriceToFare(p && p.price);
    if(g){
      값 = g['값'];
      단위 = 단위 || g['단위'];
      덧말 = 덧말 || g['덧말'];
      부터 = false;
    }
  }

  /* 금액이 전혀 없는 상품 — 눌러서 바로 예약문의로 갑니다 */
  if(값 == null){
    return `<button type="button" class="price-chip" onclick="event.preventDefault();event.stopPropagation();location.href='contact.html';">가격 문의<span class="price-cta-label">예약문의 하러 가기 →</span></button>`;
  }

  /* 상세 쪽 요금 상자와 같은 순서입니다 — 작은 설명줄 → 큰 금액 → / 1인 */
  const 칸 = 단위 || '1인';
  const 설명 = 덧말 ? `${칸} 요금 · ${덧말}` : `${칸} 요금`;
  const 뒤 = 부터 ? `/ ${칸} 부터` : `/ ${칸}`;
  const 원 = euWon(값);
  return `<span class="price-chip">` +
         `<span class="price-eyebrow">${설명}</span>` +
         `<span class="price-main">` +
           `<b class="price-eur">${euCardMoney(값)}</b>` +
           `<i class="price-per">${뒤}</i>` +
         `</span>` +
         (원 ? `<span class="price-krw" data-eurkrw="${값}">${원}</span>` : '') +
         `</span>`;
}

